import assert from "node:assert/strict";
import {evaluatePayAppRelease} from "./payapp-release-gates.mjs";
const digest="a".repeat(64),payapp={id:"PA-1",projectId:"orchard",status:"contractor_signed",documentDigest:digest};
const actor={id:"gc-1",authenticated:true,projectId:"orchard"};
const signatures=[{payappId:"PA-1",projectId:"orchard",role:"contractor",documentDigest:digest,verified:true,signedAt:"2026-10-13T00:00:00Z"}];
const auditEvents=[{payappId:"PA-1",projectId:"orchard",type:"document_locked",documentDigest:digest}];
const base={payapp,actor,validation:{valid:true,issues:[]},signatures,auditEvents};
assert.deepEqual(evaluatePayAppRelease(base).nextAction,"submit_to_owner");
assert.equal(evaluatePayAppRelease(base).ready,true);
assert.equal(evaluatePayAppRelease({...base,actor:{...actor,projectId:"other"}}).ready,false);
assert.equal(evaluatePayAppRelease({...base,validation:{valid:false,issues:[{code:"ERROR"}]}}).ready,false);
assert.equal(evaluatePayAppRelease({...base,signatures:[]}).ready,false);
assert.equal(evaluatePayAppRelease({...base,auditEvents:[]}).ready,false);
assert.equal(evaluatePayAppRelease({...base,payapp:{...payapp,documentDigest:"b".repeat(64)}}).ready,false);
assert.equal(evaluatePayAppRelease({...base,payapp:{...payapp,status:"owner_approved"}}).ready,false);
assert.equal(evaluatePayAppRelease({...base,payapp:{...payapp,status:"owner_approved"},signatures:[...signatures,{...signatures[0],role:"owner"}]}).nextAction,"submit_to_lender");
assert.equal(evaluatePayAppRelease({...base,signatures:[{...signatures[0],revoked:true}]}).ready,false);
assert.equal(evaluatePayAppRelease({}).ready,false);
console.log("Payapp release gate checks passed");
