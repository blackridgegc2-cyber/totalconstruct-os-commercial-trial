import assert from "node:assert/strict";
import {authorizePayAppTransition as check} from "./payapp-transition-policy.mjs";
const digest="a".repeat(64),payapp={id:"PA-1",projectId:"orchard",status:"contractor_signed",documentDigest:digest,version:2};
const actor={id:"gc",authenticated:true,projectId:"orchard",role:"contractor"};
const signatures=["contractor","owner","lender"].map(role=>({payappId:"PA-1",projectId:"orchard",role,documentDigest:digest,verified:true,signedAt:"2026-10-13T00:00:00Z"}));
const auditEvents=[{payappId:"PA-1",projectId:"orchard",type:"document_locked",documentDigest:digest}];
const base={action:"submit_to_owner",payapp,actor,validation:{valid:true,issues:[]},signatures,auditEvents,expectedVersion:2,requestId:"test-request-001"};
assert.equal(check(base).allowed,true);
assert.equal(check(base).nextStatus,"owner_pending");
assert.equal(check({...base,expectedVersion:1}).allowed,false);
assert.equal(check({...base,requestId:"short"}).allowed,false);
assert.equal(check({...base,actor:{...actor,role:"owner"}}).allowed,false);
assert.equal(check({...base,actor:{...actor,projectId:"other"}}).allowed,false);
assert.equal(check({...base,payapp:{...payapp,status:"owner_pending"}}).allowed,false);
const owner={...base,action:"approve_owner",payapp:{...payapp,status:"owner_pending"},actor:{...actor,role:"owner"}};
assert.equal(check(owner).nextStatus,"owner_approved");
assert.equal(check({...owner,signatures:signatures.filter(x=>x.role!=="owner")}).allowed,false);
const lender={...base,action:"approve_lender",payapp:{...payapp,status:"lender_pending"},actor:{...actor,role:"lender"}};
assert.equal(check(lender).nextStatus,"lender_approved");
assert.equal(check({...lender,signatures:signatures.filter(x=>x.role!=="owner")}).allowed,false);
assert.equal(check({...lender,signatures:signatures.filter(x=>x.role!=="lender")}).allowed,false);
assert.equal(check({...base,action:"unknown"}).allowed,false);
console.log("Payapp transition policy checks passed");
